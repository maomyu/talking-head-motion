#!/usr/bin/env python3
"""Fetch the reviewed OFL font snapshot into a project, without OS installation.

Standard library only. Both font and license must match the registry SHA-256.
No style profile is selected or generated by this helper.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from urllib.parse import urlparse
from urllib.request import Request, urlopen
import zipfile

REGISTRY = Path(__file__).resolve().parents[1] / 'assets/fonts/registry.json'


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_registry(path: Path) -> dict:
    data = json.loads(path.read_text(encoding='utf-8'))
    if data.get('schema_version') != 1 or not data.get('fonts'):
        raise ValueError('Unsupported or empty font registry')
    ids = set()
    for row in data['fonts']:
        if row['id'] in ids or row['license']['id'] != 'OFL-1.1':
            raise ValueError('Registry must have unique IDs and reviewed OFL-1.1 fonts')
        ids.add(row['id'])
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_-]*', row['css_family']):
            raise ValueError('Invalid CSS family alias')
        for resource in (row['source'], row['font'], row['license']):
            if not re.fullmatch(r'[0-9a-f]{64}', resource['sha256']):
                raise ValueError('Missing SHA-256 for ' + row['id'])
            if not isinstance(resource['bytes'], int) or resource['bytes'] <= 0:
                raise ValueError('Missing exact size for ' + row['id'])
        for resource in (row['source'], row['license']):
            official_url(resource['url'])
    return data


def official_url(url: str) -> None:
    host = urlparse(url).hostname or ''
    if urlparse(url).scheme != 'https' or not (host == 'github.com' or host == 'raw.githubusercontent.com' or host.endswith('.githubusercontent.com')):
        raise ValueError('Registry download must use the reviewed official HTTPS source')


def verified(data: bytes, resource: dict) -> bool:
    return len(data) == resource['bytes'] and sha(data) == resource['sha256']


def fetch(resource: dict) -> bytes:
    official_url(resource['url'])
    request = Request(resource['url'], headers={'User-Agent': 'talking-head-motion-font-fetch/1.0'})
    chunks, count = [], 0
    with urlopen(request, timeout=30) as response:
        official_url(response.geturl())
        while True:
            chunk = response.read(1024 * 1024)
            if not chunk:
                break
            count += len(chunk)
            if count > resource['bytes']:
                raise ValueError('Upstream size changed: ' + resource['url'])
            chunks.append(chunk)
    data = b''.join(chunks)
    if not verified(data, resource):
        raise ValueError('Upstream SHA-256/size mismatch; review the source before updating the registry: ' + resource['url'])
    return data


def project_path(destination: Path, relative: str) -> Path:
    path = (destination / relative).resolve()
    if not path.is_relative_to(destination) or path == destination:
        raise ValueError('Font output path escapes destination')
    return path


def cached(path: Path, resource: dict, replace_invalid: bool) -> bool:
    if not path.exists():
        return False
    if path.is_file() and verified(path.read_bytes(), resource):
        return True
    if not replace_invalid:
        raise ValueError(f'Existing file differs from the reviewed snapshot: {resource["path"]}; inspect it, then use --replace-invalid if replacement is intended')
    return False


def atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.' + path.name + '.', suffix='.part', delete=False) as output:
            temporary = Path(output.name)
            output.write(data)
        os.replace(temporary, path)
    finally:
        if temporary and temporary.exists():
            temporary.unlink()


def install_font(row: dict, destination: Path, verify_only: bool, replace_invalid: bool) -> dict:
    font, license = row['font'], row['license']
    font_path, license_path = project_path(destination, font['path']), project_path(destination, license['path'])
    font_cached = cached(font_path, font, replace_invalid and not verify_only)
    license_cached = cached(license_path, license, replace_invalid and not verify_only)
    if verify_only:
        if not font_cached or not license_cached:
            raise ValueError('Missing font or license: ' + row['id'])
    else:
        font_data = license_data = None
        if not font_cached:
            downloaded = fetch(row['source'])
            if row['source']['format'] == 'zip':
                # Read only the named member; never extract archive paths to disk.
                with zipfile.ZipFile(io.BytesIO(downloaded)) as archive:
                    info = archive.getinfo(font['archive_member'])
                    if info.file_size != font['bytes']:
                        raise ValueError('Archive font size changed: ' + row['id'])
                    font_data = archive.read(info)
            else:
                font_data = downloaded
            if not verified(font_data, font):
                raise ValueError('Font SHA-256 mismatch: ' + row['id'])
        if not license_cached:
            license_data = fetch(license)
        # Resolve and verify both resources before replacing either output.
        if font_data is not None:
            atomic_write(font_path, font_data)
        if license_data is not None:
            atomic_write(license_path, license_data)
    return {'id': row['id'], 'family': row['css_family'], 'font': font['path'], 'font_sha256': font['sha256'],
            'license': license['id'], 'license_file': license['path'], 'license_sha256': license['sha256'],
            'source': row['source']['url'], 'cached_font': font_cached, 'cached_license': license_cached}


def font_css(rows: list[dict]) -> str:
    lines = ['/* These fonts retain their OFL-1.1 licenses in licenses/. No style profiles are defined here. */']
    for row in rows:
        weights = row['weights']
        weight = f'{weights["min"]:g} {weights["max"]:g}' if isinstance(weights, dict) else str(weights[0])
        format = 'woff2' if row['font']['path'].endswith('.woff2') else 'truetype'
        lines.append('@font-face{font-family:' + row['css_family'] + ';src:url("' + row['font']['path'] + '") format("' + format + '");font-weight:' + weight + ';font-style:normal;font-display:block;}')
    return '\n'.join(lines) + '\n'


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--registry', type=Path, default=REGISTRY)
    choice = parser.add_mutually_exclusive_group(required=True)
    choice.add_argument('--list', action='store_true', help='List reviewed font IDs without writing or downloading')
    choice.add_argument('--fonts', nargs='+', metavar='ID', help='Only fetch these registry IDs')
    choice.add_argument('--all', action='store_true', help='Fetch/verify every reviewed OFL font')
    parser.add_argument('--dest', type=Path, help='Project font directory; never a system font directory')
    parser.add_argument('--verify-only', action='store_true', help='Read-only verification; no network, output files or CSS changes')
    parser.add_argument('--replace-invalid', action='store_true', help='Replace selected local mismatches after downloading the exact reviewed bytes')
    args = parser.parse_args(argv)
    try:
        registry = read_registry(args.registry)
        if args.list:
            print(json.dumps({'fonts': [{k: row[k] for k in ('id', 'name', 'category', 'css_family', 'weights', 'homepage')} for row in registry['fonts']]}, ensure_ascii=False, indent=2))
            return 0
        if not args.dest:
            parser.error('--dest is required for downloading or verification')
        selected = set(args.fonts or [row['id'] for row in registry['fonts']])
        missing = selected - {row['id'] for row in registry['fonts']}
        if missing:
            raise ValueError('Unknown font IDs: ' + ', '.join(sorted(missing)))
        rows = [row for row in registry['fonts'] if row['id'] in selected]
        destination = args.dest.expanduser().resolve()
        records, errors = [], []
        for row in rows:
            try:
                records.append(install_font(row, destination, args.verify_only, args.replace_invalid))
            except (OSError, ValueError, KeyError, zipfile.BadZipFile) as error:
                errors.append({'id': row['id'], 'error': str(error)})
        generated = []
        if not errors and not args.verify_only:
            # Adding a font must retain earlier, still-verified registrations.
            available, installed = [], []
            selected_records = {row['id']: row for row in records}
            for row in registry['fonts']:
                resources = (row['font'], row['license'])
                if all((path := project_path(destination, resource['path'])).is_file() and verified(path.read_bytes(), resource) for resource in resources):
                    available.append(row)
                    installed.append(selected_records.get(row['id']) or install_font(row, destination, True, False))
            atomic_write(destination / 'fonts.css', font_css(available).encode())
            manifest = {'registry_sha256': sha(args.registry.read_bytes()), 'fonts': installed,
                        'scope': 'Verified OFL font cache; no system installation or style profiles'}
            atomic_write(destination / 'font-manifest.json', (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode())
            generated = ['fonts.css', 'font-manifest.json']
        print(json.dumps({'status': 'failed' if errors else 'ready', 'mode': 'verify-only' if args.verify_only else 'download', 'fonts': records, 'generated': generated, 'errors': errors}, ensure_ascii=False, indent=2))
        return 1 if errors else 0
    except (OSError, ValueError, KeyError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
